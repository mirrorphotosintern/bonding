export function getGameById(id: string): ConversationGame | undefined {
  return conversationGames.find((g) => g.id === id);
}

export function getGamesBySituation(situation: string): ConversationGame[] {
  return conversationGames.filter((g) => g.fit.situations.includes(situation as any));
}
