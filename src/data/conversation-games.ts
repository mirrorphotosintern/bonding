  Partial<ConversationGame>;

function readyGame(seed: GameSeed): ConversationGame {
  return {
    traditionalNames: [],
    originNotes: "Family game with Try This cooperative rules",
    fit: {
      situations: ["car", "restaurant", "queue", "bedtime", "dinner"],
      volume: "quiet",
      interruptibility: "immediate",
      cognitiveLoad: "low",
      driverSafe: true,
      languageCodes: ["en"],
    },
    ageBands: ["5-6", "7-8", "9-10"],
    durationMinutes: [5, 15],
    adultModel: "I'll take the first turn so everyone can see how it works.",
    cooperativeDefault: true,
    passAllowed: true,
    easier: "Offer two choices or solve the first turn together.",
    harder: "Add a time limit or one extra rule.",
    mixedAges: "The youngest chooses or leads; older players help without taking over.",
    childRemix: "Let the child change one rule for the next round.",
    noVision: "Playable through sound and description.",
    lowSpeech: "Pointing, gestures, or one-word answers are welcome.",
    closeLine: "Which turn should we remember?",
    ...seed,
  };
}

